#!/bin/bash
# make_nuwro_beam.sh <gibuu flux .dat> <pdg> > beam.txt
# Converts a GiBUU flux table (bin centres in GeV, uniform bins) into a NuWro
# beam_type=0 spectrum (beam_energy = Emin Emax f1 ... fn, MeV), so that NuWro and
# GiBUU are generated with exactly the same flux shape.
awk -v pdg="$2" -v src="$1" 'BEGIN { n = 0 }
  !/^#/ && NF>=2 { e[n]=$1; f[n]=$2; n++ }
  END {
    w = e[1]-e[0]
    for (i=1;i<n;i++) if ((e[i]-e[i-1])/w < 0.999 || (e[i]-e[i-1])/w > 1.001) { print "non-uniform bins" > "/dev/stderr"; exit 1 }
    last = n-1; while (last>0 && f[last]==0) last--          # drop trailing empty bins
    emin = sprintf("%.3f", (e[0]-w/2)*1000)+0; emax = sprintf("%.3f", (e[last]+w/2)*1000)+0
    printf "# generated by make_nuwro_beam.sh from %s\n", src
    printf "beam_type = 0\nbeam_particle = %d\nbeam_direction = 0 0 1\n", pdg
    printf "beam_energy = %g %g", emin, emax
    for (i=0;i<=last;i++) printf " %g", f[i]
    printf "\n"
  }' "$1"
